def build_harness(root: Path, temporary: Path, compiler: str) -> ctypes.CDLL:
    fieldmap = (root / 'src/fieldmap.c').read_text()
    camera = (root / 'src/field_camera.c').read_text()
    definitions = functions_from(fieldmap) | functions_from(camera)
    stubbed = {'MapGridGetMetatileLayerTypeAt'}
    seeds = {'InitMapLayoutData', 'CameraMove', 'CameraUpdate',
             'CameraUpdateNoObjectRefresh', 'ResetCameraOffset', 'DrawWholeMapView',
             'GetBorderBlockAt', 'MapGridGetMetatileIdAt', 'MapGridSetMetatileEntryAt',
             'LoadSavedMapView'}
    selected = set()
    pending = list(seeds)
    while pending:
        name = pending.pop()
        if name in selected or name in stubbed:
            continue
        if name not in definitions:
            raise RuntimeError(f'Production C function not found: {name}')
        selected.add(name)
        body = mask_comments_and_strings(definitions[name][1])
        pending.extend(n for n in re.findall(r'\b(\w+)\s*\(', body)
                       if n in definitions and n not in selected and n not in stubbed)
    macros = []
    for filename in ['include/fieldmap.h','include/global.fieldmap.h','include/constants/metatile_labels.h']:
        for line in (root / filename).read_text().splitlines():
            if line.startswith('#define ') and not any(x in line for x in ['GUARD_', 'METATILE_ID(', '\\']):
                macros.append(line)
    declarations = '\n'.join(definitions[n][0] + ';' for n in sorted(selected))
    source = '\n'.join(macros) + '\n' + SHIM + '\n' + declarations + '\n'
    source += '\n'.join(definitions[n][1] for n in sorted(selected)) + '\n' + WRAPPERS
    c_path = temporary / 'transition_harness.c'
    library_path = temporary / 'transition_harness.so'
    c_path.write_text(source)
    build = subprocess.run([compiler, '-std=c99', '-O1', '-g', '-shared', '-fPIC',
                            '-Wall', '-Wno-unused-function', '-Wno-unused-variable',
                            '-o', str(library_path), str(c_path)], capture_output=True, text=True)
    if build.returncode:
        raise RuntimeError('Host C harness compilation failed:\n' + build.stderr)
    library = ctypes.CDLL(str(library_path))
    u16p = ctypes.POINTER(ctypes.c_uint16)
    library.h_map.argtypes = [ctypes.c_int,u16p,u16p]
    library.h_meta.argtypes = [ctypes.c_int,u16p,ctypes.c_int,u16p,ctypes.c_int]
    library.h_init.argtypes = [ctypes.c_int] * 6
    library.h_step.argtypes = [ctypes.c_int] * 3
    library.h_grid.argtypes = [u16p]
    library.h_bg.argtypes = [u16p]
    library.h_mutate.argtypes = [ctypes.c_int,ctypes.c_int,ctypes.c_uint16]
    library.h_state.argtypes = [ctypes.POINTER(ctypes.c_int)]
    library.h_restore_view.argtypes = [u16p]
    library.h_save_view.argtypes = [u16p]
    for name in ['h_map','h_meta','h_init','h_step','h_grid','h_bg','h_redraw','h_mutate','h_state',
                 'h_restore_view','h_save_view']:
        getattr(library,name).restype = None
    return library


def words(path: Path) -> list[int]:
    data = path.read_bytes()
    return list(struct.unpack(f'<{len(data)//2}H',data))


def as_c_words(values: list[int]):
    return (ctypes.c_uint16 * len(values))(*values)


def load_data(lib: ctypes.CDLL, root: Path) -> list[list[int]]:
    maps = []
    for index,name in enumerate(['PonteValleLaricia','Laricia']):
        data = words(root / 'data/layouts' / name / 'map.bin')
        border = words(root / 'data/layouts' / name / 'border.bin')
        if len(data) != 4096 or len(border) != 4:
            raise RuntimeError(f'{name}: expected a 64 x 64 map and a 2 x 2 border')
        maps.append(data)
        lib.h_map(index,as_c_words(data),as_c_words(border))
    for index,directory in enumerate(['primary/general','secondary/ponte_valle_laricia','secondary/laricia_ponte']):
        base = root / 'data/tilesets' / directory
        meta,attr = words(base / 'metatiles.bin'),words(base / 'metatile_attributes.bin')
        if len(meta)>4096 or len(attr)>512:
            raise RuntimeError(f'{directory}: exceeds the Emerald tileset limits')
        lib.h_meta(index,as_c_words(meta),len(meta),as_c_words(attr),len(attr))
    return maps


def get_array(lib: ctypes.CDLL, name: str, length: int) -> list[int]:
    out = (ctypes.c_uint16 * length)()
    getattr(lib,name)(out)
    return list(out)


def state(lib: ctypes.CDLL) -> tuple[int,...]:
    out = (ctypes.c_int * 5)()
    lib.h_state(out)
    return tuple(out)


def validate(lib: ctypes.CDLL, maps: list[list[int]]) -> dict:
    width,height = 79,78
    failures = []
    checks = {'grid_crossings':0,'dynamic_crossings':0,'render_crossings':0,
              'ordinary_camera_updates':0,'round_trips':0,'legacy_save_reloads':0,
              'correct_save_reloads':0,'dynamic_save_reloads':0}
    difference_counts = {'grid_cells':0,'bg_words':0}

    def compare(actual, expected, context, category):
        differences = [i for i,(a,b) in enumerate(zip(actual,expected)) if a!=b]
        if differences:
            difference_counts[category] += len(differences)
            if len(failures)<16:
                i=differences[0]
                failures.append(f'{context}: {len(differences)} mismatches; first index {i}: '
                                f'actual 0x{actual[i]:04X}, expected 0x{expected[i]:04X}')

    for source,dx in [(0,1),(1,-1)]:
        dest=1-source
        old_x,new_x=(63,0) if dx==1 else (0,63)
        for row in range(64):
            lib.h_init(dest,new_x,row,0,0,0)
            canonical=get_array(lib,'h_grid',width*height)
            lib.h_init(source,old_x,row,0,0,0)
            lib.h_step(dx,0,0)
            actual=get_array(lib,'h_grid',width*height)
            compare(actual,canonical,f'grid {source}->{dest}, row {row}','grid_cells')
            checks['grid_crossings']+=1
            if state(lib)[:2] != (new_x,row) or state(lib)[4] != dest:
                failures.append(f'Wrong transition coordinates at {source}->{dest}, row {row}')

        # Two view mutations: one in the source map, one in the already visible
        # neighbor. Both must survive, including collision and elevation bits.
        for row in [14,17,38,41]:
            lib.h_init(dest,new_x,row,0,0,0)
            expected=get_array(lib,'h_grid',width*height)
            lib.h_init(source,old_x,row,0,0,0)
            source_positions=[old_x+6,old_x+8]
            values=[0xA80D,0x5C16]
            for x,value in zip(source_positions,values):
                lib.h_mutate(x,row+7,value)
                new_grid_x=x-64 if dx==1 else x+64
                expected[(row+7)*width+new_grid_x]=value
            lib.h_step(dx,0,0)
            compare(get_array(lib,'h_grid',width*height),expected,
                    f'dynamic {source}->{dest}, row {row}','grid_cells')
            checks['dynamic_crossings']+=1

        for mode in [1,2]:
            for row in [14,15,16,17,38,39,40,41]:
                for ring_x,ring_y in [(0,0),(30,28),(14,10)]:
                    lib.h_init(source,old_x,row,0,ring_x,ring_y)
                    lib.h_step(dx,0,mode)
                    actual=get_array(lib,'h_bg',3072)
                    expected_state=((ring_x+dx*2)%32,ring_y)
                    if state(lib)[2:4] != expected_state:
                        failures.append(f'Camera ring offset reset at mode {mode}, {source}->{dest}, row {row}')
                    lib.h_redraw()
                    compare(actual,get_array(lib,'h_bg',3072),
                            f'BG mode {mode}, {source}->{dest}, row {row}, ring {ring_x}/{ring_y}',
                            'bg_words')
                    checks['render_crossings']+=1

        for row in [14,17,38,41]:
            lib.h_init(source,old_x,row,0,12,22)
            initial=get_array(lib,'h_grid',width*height)
            lib.h_step(dx,0,1)
            lib.h_step(-dx,0,1)
            compare(get_array(lib,'h_grid',width*height),initial,
                    f'round trip from {source}, row {row}','grid_cells')
            rendered=get_array(lib,'h_bg',3072)
            lib.h_redraw()
            compare(rendered,get_array(lib,'h_bg',3072),
                    f'round trip BG from {source}, row {row}','bg_words')
            checks['round_trips']+=1

    # Ordinary scrolling must keep its original partial redraw contract.
    # Compare the visible 15 x 14 metatile rectangle, excluding the retained
    # off-screen ring edge that the stock renderer deliberately does not fill.
    for mode in [1,2]:
        for dx,dy in [(1,0),(-1,0),(0,1),(0,-1)]:
            lib.h_init(0,24,24,0,18,26)
            lib.h_step(dx,dy,mode)
            actual=get_array(lib,'h_bg',3072)
            lib.h_redraw()
            expected=get_array(lib,'h_bg',3072)
            _,_,ring_x,ring_y,_=state(lib)
            visible=[bg*1024+((ring_y+y)%32)*32+(ring_x+x)%32
                     for bg in range(3) for y in range(28) for x in range(30)]
            compare([actual[i] for i in visible],[expected[i] for i in visible],
                    f'ordinary BG mode {mode}, step {dx}/{dy}','bg_words')
            checks['ordinary_camera_updates']+=1
        for source,dx in [(0,1),(1,-1)]:
            old_x,new_x=(63,0) if dx==1 else (0,63)
            lib.h_init(1-source,new_x,15,1,0,0)
            canonical=get_array(lib,'h_grid',width*height)
            lib.h_init(source,old_x,15,1,12,22)
            lib.h_step(dx,0,mode)
            compare(get_array(lib,'h_grid',width*height),canonical,
                    f'same tileset mode {mode}, {source}->{1-source}','grid_cells')
            checks['ordinary_camera_updates']+=1

    legacy=zlib.decompress(base64.b64decode(LEGACY_VIEWS))
    cursor=0
    while cursor<len(legacy):
        map_index,x,y,count=struct.unpack_from('<4H',legacy,cursor)
        cursor+=8
        view=list(struct.unpack_from(f'<{count}H',legacy,cursor))
        cursor+=count*2
        lib.h_init(map_index,x,y,0,0,0)
        canonical=get_array(lib,'h_grid',width*height)
        correct_view=get_array(lib,'h_save_view',210)
        lib.h_restore_view(as_c_words(view))
        compare(get_array(lib,'h_grid',width*height),canonical,
                f'legacy save map {map_index}, row {y}','grid_cells')
        checks['legacy_save_reloads']+=1

        # Correct saves and repeated loads must remain exactly unchanged.
        for attempt in range(2):
            lib.h_init(map_index,x,y,0,0,0)
            lib.h_restore_view(as_c_words(correct_view))
            compare(get_array(lib,'h_grid',width*height),canonical,
                    f'correct save map {map_index}, row {y}, reload {attempt}','grid_cells')
            correct_view=get_array(lib,'h_save_view',210)
            checks['correct_save_reloads']+=1

        # Preserve in-game map changes on both sides of the boundary while
        # repairing the historical aliases around them.
        expected=canonical[:]
        for column,value in [(7,0xA80D),(1 if map_index==1 else 13,0x5C16)]:
            view[7*15+column]=value
            expected[(y+7)*width+x+column]=value
        lib.h_init(map_index,x,y,0,0,0)
        lib.h_restore_view(as_c_words(view))
        compare(get_array(lib,'h_grid',width*height),expected,
                f'dynamic save map {map_index}, row {y}','grid_cells')
        checks['dynamic_save_reloads']+=1

    crossings=[y for y in range(64)
               if (maps[0][y*64+63]&0xC00)==0 and (maps[1][y*64]&0xC00)==0]
    return {'status':'FAIL' if any(difference_counts.values()) or failures else 'PASS',
            'checks':checks,'walkable_boundary_rows':crossings,
            'differences':difference_counts,'first_failures':failures}


