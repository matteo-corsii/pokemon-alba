    parser.add_argument('--json',type=Path,help='Optional JSON result path')
    args=parser.parse_args()
    compiler=shutil.which(args.cc)
    if compiler is None:
        parser.error(f'Host C compiler not found: {args.cc}')
    with tempfile.TemporaryDirectory(prefix='alba-transition-') as directory:
        lib=build_harness(args.repository_root,Path(directory),compiler)
