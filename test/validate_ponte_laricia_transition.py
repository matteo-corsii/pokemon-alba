def mask_comments_and_strings(text: str) -> str:
    token = r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\''
    return re.sub(token, lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]), text)


def functions_from(text: str) -> dict[str, tuple[str, str]]:
    masked = mask_comments_and_strings(text)
    pattern = re.compile(r'^([\w \t*]+?\b(\w+)\s*\([^;{}]*\))\s*\n\{', re.M)
    result = {}
    for match in pattern.finditer(masked):
        brace = masked.index('{', match.start())
        depth, end = 1, brace + 1
        while depth:
            depth += (masked[end] == '{') - (masked[end] == '}')
            end += 1
        result[match[2]] = (text[match.start():brace].strip(), text[match.start():end])
    return result


